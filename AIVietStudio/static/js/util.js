export function isVi(t) {
  const L = [...String(t).normalize("NFC").toLowerCase()].filter((c) => /\p{L}/u.test(c));
  if (L.length < 3) return null;
  return L.filter((c) => VI.has(c)).length / L.length >= 0.05;
}

